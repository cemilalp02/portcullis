// Builds the assets of the HTML report that Go embeds (internal/report/html):
//
//   style.css  Tailwind CSS compiled from input.css for the classes used in
//              report.tmpl, app.js and html.go, minified.
//   icons.svg  An SVG sprite of the Lucide icons the report references as
//              "#i-name" (template) or "i-name" (Go), one <symbol> each.
//
// Run with `npm ci && npm run build` in this directory. The outputs are
// committed, so building Portcullis needs no Node.js.
import { compile, optimize } from "@tailwindcss/node";
import { Scanner } from "@tailwindcss/oxide";
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, "../../internal/report/html");
const require = createRequire(import.meta.url);

// ---- CSS
const input = readFileSync(join(here, "input.css"), "utf8");
const compiler = await compile(input, { base: here, onDependency() {} });
const sources = compiler.root === "none" ? [] : compiler.root === null
  ? [{ base: here, pattern: "**/*", negated: false }]
  : [{ ...compiler.root, negated: false }];
const scanner = new Scanner({ sources: sources.concat(compiler.sources) });
const candidates = scanner.scan();
const { code } = optimize(compiler.build(candidates), { minify: true });
const banner = "/* Generated by web/report/build.mjs from web/report/input.css. Do not edit. */\n";
writeFileSync(join(out, "style.css"), banner + code.trim() + "\n");

// ---- Icons
const icons = new Set();
for (const file of ["report.tmpl", "../html.go"]) {
  const text = readFileSync(join(out, file), "utf8");
  for (const m of text.matchAll(/[#"]i-([a-z][a-z0-9-]*)"/g)) icons.add(m[1]);
}
const dir = join(dirname(require.resolve("lucide-static/package.json")), "icons");
const version = JSON.parse(readFileSync(join(dir, "../package.json"), "utf8")).version;
const symbols = [...icons].sort().map((name) => {
  const svg = readFileSync(join(dir, `${name}.svg`), "utf8");
  const inner = svg.slice(svg.indexOf(">", svg.indexOf("<svg")) + 1, svg.lastIndexOf("</svg>"))
    .replace(/\s+/g, " ").replace(/> </g, "><").replace(/ \/>/g, "/>").trim();
  return `<symbol id="i-${name}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" ` +
    `stroke-linecap="round" stroke-linejoin="round">${inner}</symbol>`;
});
writeFileSync(join(out, "icons.svg"),
  `<!-- Lucide ${version} (ISC License, https://lucide.dev), generated by web/report/build.mjs. Do not edit. -->\n` +
  symbols.join("\n") + "\n");

console.log(`style.css: ${code.length} bytes, ${candidates.length} candidates; icons.svg: ${symbols.length} icons`);
