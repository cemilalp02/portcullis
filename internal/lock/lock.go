// Package lock reads, writes and compares context.lock files: the approved
// hashes of every agent context file in a repository (docs/FILE_FORMATS.md,
// ADR-0008, REQUIREMENTS FR-50..FR-54).
package lock

import (
	"bufio"
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"strings"
	"unicode/utf8"

	"github.com/cemilalp02/portcullis/internal/escape"
)

// File names and fixed lines of the format.
const (
	FileName   = "context.lock"
	Header     = "# context.lock — generated by portcullis; review changes to this file like code."
	FormatLine = "portcullis-lock 1"
)

// Entry is one approved file.
type Entry struct {
	Path string // '/'-separated, relative to the repository root
	Hash string // "sha256:<64 hex digits>"
}

// File is a parsed context.lock.
type File struct {
	Ruleset string // rule-set version used when the files were approved
	Forced  bool   // approved with --force despite findings at or above the threshold
	Entries []Entry
}

// Source is a file to hash: Path is recorded, ReadPath is read (they differ
// for links that resolve inside the root).
type Source struct {
	Path     string
	ReadPath string
}

// Hash returns "sha256:<hex>" of r with every CRLF replaced by LF, so the same
// commit hashes identically with and without git's autocrlf (FR-51). Nothing
// else is normalised. Input is streamed, never held in memory.
func Hash(r io.Reader) (string, error) {
	h := sha256.New()
	buf := make([]byte, 64<<10)
	pendingCR := false
	for {
		n, err := r.Read(buf)
		b := buf[:n]
		start := 0
		for i := range b {
			if pendingCR {
				pendingCR = false
				if b[i] != '\n' {
					h.Write([]byte{'\r'})
				}
			}
			if b[i] == '\r' {
				h.Write(b[start:i])
				start = i + 1
				pendingCR = true
			}
		}
		h.Write(b[start:])
		if errors.Is(err, io.EOF) {
			break
		}
		if err != nil {
			return "", err
		}
	}
	if pendingCR {
		h.Write([]byte{'\r'})
	}
	return "sha256:" + hex.EncodeToString(h.Sum(nil)), nil
}

// Compute hashes every source, reading through os.Root so nothing outside
// root can be read. Entries are sorted by path.
func Compute(root string, sources []Source) ([]Entry, error) {
	r, err := os.OpenRoot(root)
	if err != nil {
		return nil, err
	}
	defer r.Close()
	entries := make([]Entry, 0, len(sources))
	for _, s := range sources {
		f, err := r.Open(filepath.FromSlash(s.ReadPath))
		if err != nil {
			return nil, fmt.Errorf("%s: %w", s.Path, err)
		}
		sum, err := Hash(f)
		_ = f.Close()
		if err != nil {
			return nil, fmt.Errorf("%s: %w", s.Path, err)
		}
		entries = append(entries, Entry{Path: s.Path, Hash: sum})
	}
	slices.SortFunc(entries, func(a, b Entry) int { return strings.Compare(a.Path, b.Path) })
	return entries, nil
}

func needsQuote(p string) bool {
	return p == "" || strings.HasPrefix(p, `"`) || strings.TrimSpace(p) != p || !utf8.ValidString(p) ||
		strings.ContainsFunc(p, func(r rune) bool { return r != ' ' && !escape.Visible(r) })
}

// Format renders the file in its canonical form.
func Format(f File) []byte {
	var b bytes.Buffer
	fmt.Fprintf(&b, "%s\n%s\nruleset %s\nforced %t\n", Header, FormatLine, f.Ruleset, f.Forced)
	entries := slices.Clone(f.Entries)
	slices.SortFunc(entries, func(a, b Entry) int { return strings.Compare(a.Path, b.Path) })
	for _, e := range entries {
		p := e.Path
		if needsQuote(p) {
			p = strconv.Quote(p)
		}
		fmt.Fprintf(&b, "%s  %s\n", e.Hash, p)
	}
	return b.Bytes()
}

// validVersion accepts rule-set versions such as 2026.10.1: 1 to 64 letters,
// digits, dots, plus and minus signs, so that a version always survives a
// write and re-read unchanged.
func validVersion(v string) bool {
	if v == "" || len(v) > 64 {
		return false
	}
	for _, c := range []byte(v) {
		switch {
		case '0' <= c && c <= '9', 'a' <= c && c <= 'z', 'A' <= c && c <= 'Z', c == '.', c == '+', c == '-':
		default:
			return false
		}
	}
	return true
}

// Parse reads a context.lock strictly: any deviation from the format is an
// error, so a tampered or truncated file never verifies (FR-53).
func Parse(data []byte) (File, error) {
	var f File
	sc := bufio.NewScanner(bytes.NewReader(data))
	sc.Buffer(make([]byte, 64<<10), 1<<20)
	line := 0
	fail := func(format string, args ...any) (File, error) {
		return File{}, fmt.Errorf("context.lock line %d: %s", line, fmt.Sprintf(format, args...))
	}
	prev := ""
	for sc.Scan() {
		line++
		text := strings.TrimSuffix(sc.Text(), "\r") // tolerate CRLF checkouts
		switch line {
		case 1:
			if text != Header {
				return fail("unexpected header (not a portcullis context.lock?)")
			}
			continue
		case 2:
			if text != FormatLine {
				return fail("unsupported format %q (want %q)", text, FormatLine)
			}
			continue
		case 3:
			v, ok := strings.CutPrefix(text, "ruleset ")
			if !ok || !validVersion(v) {
				return fail("expected 'ruleset <version>'")
			}
			f.Ruleset = v
			continue
		case 4:
			switch text {
			case "forced true":
				f.Forced = true
			case "forced false":
			default:
				return fail("expected 'forced true' or 'forced false'")
			}
			continue
		}
		hash, p, ok := strings.Cut(text, "  ")
		if !ok || !validHash(hash) {
			return fail("expected 'sha256:<64 hex>  <path>'")
		}
		if strings.HasPrefix(p, `"`) {
			u, err := strconv.Unquote(p)
			if err != nil {
				return fail("invalid quoted path")
			}
			p = u
		} else if needsQuote(p) {
			return fail("path must be quoted")
		}
		if p == "" || strings.HasPrefix(p, "/") || slices.Contains(strings.Split(p, "/"), "..") {
			return fail("invalid path %q", p)
		}
		if len(f.Entries) > 0 && p <= prev {
			return fail("entries must be sorted and unique (%q after %q)", p, prev)
		}
		prev = p
		f.Entries = append(f.Entries, Entry{Path: p, Hash: hash})
	}
	if err := sc.Err(); err != nil {
		return File{}, fmt.Errorf("context.lock: %w", err)
	}
	if line < 4 {
		return File{}, errors.New("context.lock: truncated file")
	}
	return f, nil
}

func validHash(h string) bool {
	hexPart, ok := strings.CutPrefix(h, "sha256:")
	if !ok || len(hexPart) != 64 {
		return false
	}
	_, err := hex.DecodeString(hexPart)
	return err == nil && strings.ToLower(hexPart) == hexPart
}

// Diff compares approved entries with the current ones.
type Diff struct {
	Added, Removed, Modified []string
}

// Empty reports whether nothing changed.
func (d Diff) Empty() bool { return len(d.Added)+len(d.Removed)+len(d.Modified) == 0 }

// Compare returns what changed from approved to current.
func Compare(approved, current []Entry) Diff {
	old := make(map[string]string, len(approved))
	for _, e := range approved {
		old[e.Path] = e.Hash
	}
	var d Diff
	seen := make(map[string]bool, len(current))
	for _, e := range current {
		seen[e.Path] = true
		h, ok := old[e.Path]
		switch {
		case !ok:
			d.Added = append(d.Added, e.Path)
		case h != e.Hash:
			d.Modified = append(d.Modified, e.Path)
		}
	}
	for _, e := range approved {
		if !seen[e.Path] {
			d.Removed = append(d.Removed, e.Path)
		}
	}
	slices.Sort(d.Added)
	slices.Sort(d.Removed)
	slices.Sort(d.Modified)
	return d
}
